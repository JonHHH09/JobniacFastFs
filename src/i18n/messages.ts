/** O(1) own-key check without allocating a key array (`Object.hasOwn` needs ES2022). */
function hasOwn(target: object, key: string): boolean {
  return Object.getOwnPropertyDescriptor(target, key) !== undefined;
}

/** A message id from the catalogue. */
export type MessageId = keyof typeof messages;

/** True when the text is a catalogue id (validation messages carry ids). */
export function isMessageId(value: string): value is MessageId {
  return hasOwn(messages, value);
}

/** Renders a catalogue entry, replacing each `{name}` with the given value. */
export function formatMessage(id: MessageId, params: Record<string, string | number> = {}): string {
  return messages[id].replace(/\{(\w+)\}/g, (match, name: string) =>
    hasOwn(params, name) ? String(params[name]) : match,
  );
}
