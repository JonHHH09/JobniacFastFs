"""Generate the HTML4 entity table and the BMP digit table of jobniac-text (stdlib only).

Named references come from the W3C HTML 4.01 entity sets, which the maintainer fetches first:

- https://www.w3.org/TR/html4/HTMLlat1.ent
- https://www.w3.org/TR/html4/HTMLsymbol.ent
- https://www.w3.org/TR/html4/HTMLspecial.ent

The digit table holds the BMP code points that count as digits for numeric character references:
the Unicode decimal digits (general category Nd, from the Unicode Character Database that
``unicodedata`` ships), plus ASCII and fullwidth Latin letters A to F and a to f with values 10 to 15.
Golden vectors (crates/text/tests/golden/html.json) pin both tables.

Usage (from the repository root):

    py -I tools/text/generate_html_tables.py --w3c <dir with the three .ent files> --out crates/text/src/html

The script refuses to write unless the entity sets contain exactly 252 named references.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import unicodedata
from pathlib import Path

ENTITY_SETS = ('HTMLlat1.ent', 'HTMLsymbol.ent', 'HTMLspecial.ent')
ENTITY_PATTERN = re.compile(r'<!ENTITY\s+([A-Za-z][A-Za-z0-9]*)\s+CDATA\s+"&#(\d+);"')
EXPECTED_NAMED = 252
ISO_NOTICE = (
    'Portions (C) International Organization for Standardization 1986. Permission to copy in any form '
    'is granted for use with conforming SGML systems and applications as defined in ISO 8879, provided '
    'this notice is included in all copies.'
)


def read_entities(w3c_dir: Path) -> tuple[dict[str, int], dict[str, str]]:
    """Return the named references and the SHA-256 of each entity set file."""
    entities: dict[str, int] = {}
    digests: dict[str, str] = {}
    for file_name in ENTITY_SETS:
        data = (w3c_dir / file_name).read_bytes()
        digests[file_name] = hashlib.sha256(data).hexdigest()
        for name, value in ENTITY_PATTERN.findall(data.decode('utf-8')):
            if name in entities:
                raise SystemExit(f'duplicate entity name {name} in {file_name}')
            entities[name] = int(value)
    if len(entities) != EXPECTED_NAMED:
        raise SystemExit(f'expected {EXPECTED_NAMED} named references, found {len(entities)}')
    return entities, digests


def bmp_digits() -> list[tuple[int, int]]:
    """Return ``(code point, value)`` for every BMP digit used by numeric references, sorted."""
    values: dict[int, int] = {}
    for code_point in range(0x10000):
        if 0xD800 <= code_point <= 0xDFFF:
            continue
        decimal = unicodedata.decimal(chr(code_point), None)
        if decimal is not None:
            values[code_point] = decimal
    for base in (0x41, 0x61, 0xFF21, 0xFF41):
        for offset in range(6):
            values[base + offset] = 10 + offset
    return sorted(values.items())


def render_entities(entities: dict[str, int], digests: dict[str, str], w3c_url: str) -> str:
    lines = [
        '//! HTML 4.01 named character references.',
        '//!',
        '//! Generated by `tools/text/generate_html_tables.py`; do not edit by hand.',
        '//!',
        f'//! Source: {w3c_url}HTMLlat1.ent, {w3c_url}HTMLsymbol.ent and {w3c_url}HTMLspecial.ent',
        '//! (W3C HTML 4.01 entity sets). SHA-256 of each file as fetched:',
    ]
    lines += [f'//!   {name} {digest}' for name, digest in digests.items()]
    lines += [
        '//!',
        f'//! {ISO_NOTICE}',
        '',
        '/// Named references as `(name, Unicode scalar value)`, sorted by name for binary search.',
        'pub static HTML4_ENTITIES: &[(&str, u32)] = &[',
    ]
    for name in sorted(entities):
        lines.append(f'    ("{name}", {entities[name]}),')
    lines.append('];')
    return '\n'.join(lines) + '\n'


def render_digits(digits: list[tuple[int, int]]) -> str:
    lines = [
        '//! BMP digit values for numeric character references.',
        '//!',
        '//! Generated by `tools/text/generate_html_tables.py`; do not edit by hand.',
        '//! Derived from the Unicode Character Database (decimal digits) and the ASCII and fullwidth',
        '//! Latin letters A to F and a to f; the golden vectors pin the same table.',
        '',
        '/// `(code point, digit value)` for BMP code points, sorted by code point.',
        'pub static BMP_DIGITS: &[(u16, u8)] = &[',
    ]
    for code_point, value in digits:
        lines.append(f'    (0x{code_point:04X}, {value}),')
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n', 1)[0])
    parser.add_argument('--w3c', required=True, type=Path, help='folder with the three .ent files')
    parser.add_argument('--out', required=True, type=Path, help='folder that receives entities.rs and digits.rs')
    parser.add_argument(
        '--w3c-url',
        default='https://www.w3.org/TR/html4/',
        help='base URL of the entity sets, recorded in the generated header',
    )
    args = parser.parse_args()
    entities, digests = read_entities(args.w3c)
    digits = bmp_digits()
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'entities.rs').write_text(
        render_entities(entities, digests, args.w3c_url), encoding='utf-8', newline='\n'
    )
    (args.out / 'digits.rs').write_text(render_digits(digits), encoding='utf-8', newline='\n')
    print(f'wrote {len(entities)} named references and {len(digits)} digit entries to {args.out}', file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
